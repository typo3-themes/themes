#!/usr/bin/env bash
#
# Functional tests in docker against each supported TYPO3 version.
#
#   Build/Scripts/runTests.sh [-t <TYPO3 version>] [-p <PHP version>] [-u] [-a] [-- <phpunit arguments>]
#
#   -t  TYPO3 version (see SUPPORTED_VERSIONS in runTests.config), default: the lowest one
#   -p  PHP version, e.g. 8.3
#   -u  update the dependencies of the test project
#   -a  run against all supported TYPO3 versions
#
# Each version gets its own composer project in .Build/v<version> (path repository to this package).
# The package specific settings are in Build/Scripts/runTests.config.
#
set -euo pipefail

EXTENSION_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# shellcheck source=runTests.config
source "${EXTENSION_ROOT}/Build/Scripts/runTests.config"

TYPO3_VERSION="${SUPPORTED_VERSIONS%% *}"
PHP_VERSION=""
UPDATE=0
ALL=0

while getopts ":t:p:ua" opt; do
    case "${opt}" in
        t) TYPO3_VERSION="${OPTARG}" ;;
        p) PHP_VERSION="${OPTARG}" ;;
        u) UPDATE=1 ;;
        a) ALL=1 ;;
        *) echo "Unknown option -${OPTARG}" >&2; exit 2 ;;
    esac
done
shift $((OPTIND - 1))
if [ "${1:-}" = "--" ]; then
    shift
fi

if [ "${ALL}" -eq 1 ]; then
    failed=()
    for version in ${SUPPORTED_VERSIONS}; do
        args=(-t "${version}")
        if [ "${UPDATE}" -eq 1 ]; then
            args+=(-u)
        fi
        if ! "${BASH_SOURCE[0]}" "${args[@]}" -- "$@"; then
            failed+=("${version}")
        fi
    done
    if [ "${#failed[@]}" -gt 0 ]; then
        echo "Failed for TYPO3 ${failed[*]}" >&2
        exit 1
    fi
    echo "All TYPO3 versions passed (${SUPPORTED_VERSIONS})."
    exit 0
fi

case " ${SUPPORTED_VERSIONS} " in
    *" ${TYPO3_VERSION} "*) ;;
    *) echo "TYPO3 ${TYPO3_VERSION} is not supported by ${PACKAGE_NAME} (${SUPPORTED_VERSIONS})" >&2; exit 2 ;;
esac

case "${TYPO3_VERSION}" in
    11) CORE="^11.5"; TESTING_FRAMEWORK="^7.1"; DEFAULT_PHP="8.1" ;;
    12) CORE="^12.4"; TESTING_FRAMEWORK="^8.2"; DEFAULT_PHP="8.2" ;;
    13) CORE="^13.4"; TESTING_FRAMEWORK="^8.2 || ^9.0"; DEFAULT_PHP="8.3" ;;
    14) CORE="^14.0"; TESTING_FRAMEWORK="^9.0"; DEFAULT_PHP="8.3" ;;
    *) echo "Unsupported TYPO3 version ${TYPO3_VERSION}" >&2; exit 2 ;;
esac
PHP_VERSION="${PHP_VERSION:-${DEFAULT_PHP}}"
IMAGE="ghcr.io/typo3/core-testing-php${PHP_VERSION//./}:latest"
# BUILD_SUFFIX (runTests.config) separates variants of the test project, e.g. other libraries
BUILD_DIR=".Build/v${TYPO3_VERSION}${BUILD_SUFFIX:-}"

# composer.json of the test project
repositories="{\"type\": \"path\", \"url\": \"../..\", \"options\": {\"symlink\": true, \"versions\": {\"${PACKAGE_NAME}\": \"99.0.0\"}}}"
for repository in "${EXTRA_REPOSITORIES[@]+"${EXTRA_REPOSITORIES[@]}"}"; do
    repositories="${repositories}, ${repository}"
done
require="\"${PACKAGE_NAME}\": \"*\", \"typo3/testing-framework\": \"${TESTING_FRAMEWORK}\""
for corePackage in ${CORE_PACKAGES}; do
    require="${require}, \"typo3/cms-${corePackage}\": \"${CORE}\""
done
for package in "${EXTRA_REQUIRE[@]+"${EXTRA_REQUIRE[@]}"}"; do
    require="${require}, ${package}"
done

mkdir -p "${EXTENSION_ROOT}/${BUILD_DIR}"
cat > "${EXTENSION_ROOT}/${BUILD_DIR}/composer.json" <<EOF
{
    "name": "testing/${PACKAGE_NAME//\//-}-v${TYPO3_VERSION}",
    "description": "Generated by Build/Scripts/runTests.sh",
    "type": "project",
    "license": "GPL-2.0-or-later",
    "minimum-stability": "dev",
    "prefer-stable": true,
    "repositories": [${repositories}],
    "require": {${require}},
    "autoload-dev": {
        "psr-4": {
            "${TEST_NAMESPACE//\\/\\\\}": "../../Tests/"
        }
    },
    "config": {
        "allow-plugins": {
            "typo3/class-alias-loader": true,
            "typo3/cms-composer-installers": true
        },
        "audit": {"abandoned": "ignore"},
        "policy": {"advisories": {"block": false}},
        "bin-dir": "bin",
        "sort-packages": true
    },
    "extra": {
        "typo3/cms": {"web-dir": "public"}
    }
}
EOF

COMPOSER_COMMAND="install"
if [ "${UPDATE}" -eq 1 ] || [ ! -f "${EXTENSION_ROOT}/${BUILD_DIR}/composer.lock" ]; then
    COMPOSER_COMMAND="update"
fi

TTY_FLAG=""
if [ -t 1 ]; then
    TTY_FLAG="-t"
fi

# database: SQLite, or MariaDB for tests with MySQL specific SQL
DOCKER_DATABASE_ARGS=(-e typo3DatabaseDriver=pdo_sqlite)
NETWORK=""
DATABASE_CONTAINER=""
cleanup() {
    if [ -n "${DATABASE_CONTAINER}" ]; then
        docker rm -f "${DATABASE_CONTAINER}" >/dev/null 2>&1 || true
    fi
    if [ -n "${NETWORK}" ]; then
        docker network rm "${NETWORK}" >/dev/null 2>&1 || true
    fi
}
trap cleanup EXIT
if [ "${DATABASE:-sqlite}" = "mariadb" ]; then
    NETWORK="runtests-$$"
    DATABASE_CONTAINER="runtests-mariadb-$$"
    docker network create "${NETWORK}" >/dev/null
    docker run -d --rm --name "${DATABASE_CONTAINER}" --network "${NETWORK}" \
        -e MARIADB_ROOT_PASSWORD=funcp --tmpfs /var/lib/mysql/:rw,noexec,nosuid \
        mariadb:10.11 >/dev/null
    for _ in $(seq 1 60); do
        if docker exec "${DATABASE_CONTAINER}" mariadb-admin ping -uroot -pfuncp --silent >/dev/null 2>&1; then
            break
        fi
        sleep 1
    done
    DOCKER_DATABASE_ARGS=(--network "${NETWORK}"
        -e typo3DatabaseDriver=mysqli -e typo3DatabaseHost="${DATABASE_CONTAINER}"
        -e typo3DatabaseUsername=root -e typo3DatabasePassword=funcp -e typo3DatabaseName=func_test)
fi

echo "${PACKAGE_NAME}: TYPO3 ${TYPO3_VERSION} (${CORE}) on PHP ${PHP_VERSION}, database ${DATABASE:-sqlite}"
docker run --rm ${TTY_FLAG} \
    -u "$(id -u):$(id -g)" \
    -v "${EXTENSION_ROOT}:/app" \
    ${EXTRA_DOCKER_VOLUMES:-} \
    -w "/app/${BUILD_DIR}" \
    -e COMPOSER_CACHE_DIR=/app/.Build/.composer-cache \
    -e HOME=/tmp \
    -e XDEBUG_MODE=off \
    "${DOCKER_DATABASE_ARGS[@]}" \
    -e TYPO3_PATH_ROOT="/app/${BUILD_DIR}/public" \
    -e TYPO3_PATH_APP="/app/${BUILD_DIR}" \
    "${IMAGE}" \
    bash -c "composer ${COMPOSER_COMMAND} --no-progress --no-interaction -q && \
        php -d memory_limit=1G bin/phpunit -c /app/Build/phpunit/FunctionalTests.xml \
            --bootstrap vendor/typo3/testing-framework/Resources/Core/Build/FunctionalTestsBootstrap.php $*"
